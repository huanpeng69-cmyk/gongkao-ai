export const COMIC_STORYBOARD_PROMPT = `请生成一张“公考题目高密度手绘学习信息图”。参考优质学习笔记、手绘知识卡片和公考培训老师板书的视觉语言，把这一道题讲透。只借鉴信息组织和画面风格，不照搬任何参考图中的主题或文案。

【版式硬约束】
- 横版 16:9，整张图是一张连续的信息图海报，不是分镜漫画。
- 严禁六宫格、九宫格、3×3 网格、2×3 网格，也不要把画面平均切成相同方格。
- 白色或浅米色纸张背景，蓝黑色手绘线条，少量黄色重点条、浅蓝卡片和红色纠错标记。
- 顶部设置一个醒目的手写主标题，标题必须概括本题真正考查的内容，不能写空泛的“题目解析”。
- 上半区横向安排 4～5 张大小自然、连续衔接的编号主卡片，用粗箭头串联，依次呈现：审题抓手、条件转译、核心方法、关键推理、答案验证。卡片数量应由实际解题步骤决定，不得为了凑数重复内容。
- 每张主卡片包含：准确的小标题、2～4 条短而实的要点、必要的公式/数字/关系图、一个与本步骤直接相关的小插画，以及底部黄色“本步结论”重点条。
- 下半区设置“方法总结”带状区域，安排 3～5 张大小不一的小知识卡，提炼通用原则、速解技巧、易错点、验证方法和一句口诀；没有可靠内容的类别直接省略，不要硬凑。
- 右侧或右下角安排固定老师或学生角色站在目标点作最终总结，人物只是辅助，不得挤占解题信息。
- 使用箭头、圈画、便利贴、气泡、下划线、对勾和红叉组织信息，整体信息量大、干货密集，但层级清楚、留白适度。

【内容硬约束】
- 下方“实际题目、答案与解析”是唯一事实依据。只能使用其中明确出现或可直接推导的信息。
- 所有卡片必须围绕当前这一道题；每条文字都必须能追溯到题干、材料、选项、正确答案、原始解析或 AI 讲解。
- 正确答案必须与输入完全一致，数字、单位、公式、比例、人物关系、图形关系和逻辑方向不得改写错误。
- 优先展示真正决定答案的条件、推理链和验证过程；不要大段重复题干，不要扩写题目来源、用户作答状态或泛泛复习建议。
- 禁止通用模板废话，禁止虚构场景、知识点、公式、案例或结论，禁止加入与题目无关的 AI、科技、职场、登山隐喻等内容。
- 不得出现“【步骤1】”“【答案】”“输入题目”“待补充”等模板占位符。
- 若原解析存在信息不足或相互矛盾，只呈现能够确认的部分，不得自行补全。

【中文与视觉质量】
- 允许并必须使用简体中文；中文采用清晰、工整、较粗的手写印刷体，短句优先，字号足够大。
- 重点结论、关键公式、正确答案必须清晰可读；避免一张卡塞入过长段落。
- 生成前逐字核验所有中文。禁止伪汉字、随机笔画、错别字串、问号串、乱码和英文；某段文字无法准确书写时，宁可缩短或留白，也不能用乱码代替。
- 不出现水印、品牌标识、二维码、页码或无关装饰。

最终效果：像专业公考培训老师制作的高质量手绘知识海报，读者顺着箭头即可理解“条件如何转译—方法为何成立—怎样推出答案—如何避免错误”，重点是干货和真实解法，而不是人物表演或形式化分镜。`;

export function buildComicPrompt(content: string) {
  return `${COMIC_STORYBOARD_PROMPT}

=================
【实际题目、答案与解析：唯一事实依据】
${content.trim()}
=================
生成前终检：横版16:9；连续手绘信息图；不是六宫格或九宫格；所有内容只围绕本题；无占位符；答案、数字和公式准确；中文清晰无乱码；无英文；无水印。`;
}
